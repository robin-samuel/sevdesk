// AccountDatev returns the booking-account [Ref] for a German DATEV account
// number, ready for [VoucherPosCreate.AccountDatev]:
//
//	pos.AccountDatev = sevdesk.AccountDatev(6815) // Bürobedarf
//	pos.AccountDatev = sevdesk.AccountDatev(4400) // Erlöse 19 % USt
//
// It returns nil for a number outside the bundled snapshot.
//
// The table is a snapshot of /ReceiptGuidance/forAllAccounts taken 2026-07-29
// from a German Regelbesteuerer account on bookkeeping 2.0: 652 accounts, DATEV
// numbers 1350 to 9009, one account per number.
//
// Many names repeat across a contiguous run of numbers — 4000 to 4099 are all
// "Umsatzerlöse", 5000 to 5099 all "Aufwendungen für Roh-, Hilfs- und
// Betriebsstoffe" — because DATEV reserves whole number ranges for one P&L line
// so a business can split it by product, branch or project. Within a run the
// accounts are interchangeable as far as the API is concerned: identical name,
// identical allowed tax rules and rates. Use the first number of a run (4000)
// unless your accountant assigned specific sub-accounts. Of the 652 entries here 384
// names are distinct, and those two runs alone account for 200.
//
// The choice that does matter is between runs: 4000 "Umsatzerlöse" is generic and
// accepts several tax rules at 0/7/19%, while 4400 "Erlöse 19 % USt" is locked to
// [TaxRuleTaxableRevenue] at 19%.
//
// The guidance endpoints filter by client settings, so this is a convenience for
// the common case, not a guarantee — a Kleinunternehmer or a non-German chart is
// offered a different set, and only what your own client is offered is bookable.
// The snapshot also carries no tax-rule or tax-rate information. When you need
// either, ask [ReceiptGuidanceService] and take the account from
// [ReceiptGuide.Ref].
func AccountDatev(number int) *Ref {
	if id, ok := accountsDatevDE[number]; ok {
		return AccountDatevRef(id)
	}
	return nil
}

